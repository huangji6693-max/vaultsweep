import hashlib
import json
import os
import re
from pathlib import Path

from vaultsweep import __version__
from vaultsweep.models import SEVERITY_ORDER, Finding, ScanReport, Severity
from vaultsweep.rules import ALL_RULES

# Directories and extensions to skip
SKIP_DIRS = frozenset({
    ".git",
    ".venv",
    "venv",
    "node_modules",
    "__pycache__",
    ".pytest_cache",
    "dist",
    "build",
    "target",
    ".cargo",
})

SCAN_EXTENSIONS = frozenset({
    ".rs", ".toml", ".yaml", ".yml", ".json", ".env", ".env.example",
    ".py", ".js", ".ts", ".tsx", ".jsx", ".sh", ".md", ".txt", ".cfg",
    ".ini", ".properties", ".sql",
})

BINARY_EXTENSIONS = frozenset({
    ".wasm", ".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".zip",
    ".tar", ".gz", ".db", ".sqlite",
})

DEFAULT_BASELINE_FILENAME = ".vaultsweep-baseline"

# Matches inline suppression comments such as:
#   SECRET = "..."  # vaultsweep:ignore
#   const k = "..." // vaultsweep:ignore STELLAR-001,API-001
_INLINE_IGNORE_RE = re.compile(
    r"(?:#|//|/\*|--)\s*vaultsweep:ignore(?:\s+([A-Za-z0-9_,-]+))?",
    re.IGNORECASE,
)


def is_line_ignored(line: str, rule_id: str | None = None) -> bool:
    """Return True if `line` carries a `vaultsweep:ignore` directive matching `rule_id`."""
    match = _INLINE_IGNORE_RE.search(line)
    if not match:
        return False
    scoped_rules = match.group(1)
    if not scoped_rules or rule_id is None:
        return True
    allowed = {token.strip().upper() for token in scoped_rules.split(",") if token.strip()}
    return rule_id.upper() in allowed


def finding_fingerprint(finding: Finding) -> str:
    """Deterministic fingerprint for a finding used in `.vaultsweep-baseline`."""
    raw = f"{finding.rule_id}:{finding.file}:{finding.line}:{finding.match}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:24]


def load_baseline(baseline_path: str | Path | None) -> set[tuple[str, ...]]:
    """Load baseline suppression entries from a `.vaultsweep-baseline` file.

    Supports both JSON format (generated by `vaultsweep baseline` or JSON array/object)
    and line-delimited `<rule_id>:<file>:<line>` / `<rule_id>:<file>` / fingerprint entries.
    """
    if baseline_path is None:
        return set()
    path = Path(baseline_path)
    if not path.is_file():
        return set()

    try:
        raw_text = path.read_text(encoding="utf-8").strip()
    except OSError:
        return set()

    if not raw_text:
        return set()

    entries: set[tuple[str, ...]] = set()
    if raw_text.startswith("{") or raw_text.startswith("["):
        try:
            data = json.loads(raw_text)
            items = data.get("findings", []) if isinstance(data, dict) else data
            for item in items:
                if isinstance(item, str):
                    entries.add(("fp", item.strip()))
                elif isinstance(item, dict):
                    if "fingerprint" in item:
                        entries.add(("fp", str(item["fingerprint"])))
                    rule_id = str(item.get("rule_id", "*"))
                    file_val = str(item.get("file", ""))
                    if "line" in item and item["line"] is not None:
                        entries.add(("rfl", rule_id, file_val, str(item["line"])))
                    if "match" in item and item["match"] is not None:
                        entries.add(("rfm", rule_id, file_val, str(item["match"])))
                    if file_val and "line" not in item and "match" not in item:
                        entries.add(("rf", rule_id, file_val))
            return entries
        except json.JSONDecodeError:
            pass

    for raw_line in raw_text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split(":")]
        if len(parts) == 1:
            entries.add(("fp", parts[0]))
        elif len(parts) == 2:
            entries.add(("rf", parts[0], parts[1]))
        elif len(parts) >= 3:
            entries.add(("rfl", parts[0], parts[1], parts[2]))
    return entries


def is_suppressed_by_baseline(finding: Finding, baseline: set[tuple[str, ...]]) -> bool:
    if not baseline:
        return False
    fp = finding_fingerprint(finding)
    if ("fp", fp) in baseline:
        return True
    for rule_candidate in (finding.rule_id, "*"):
        if ("rfl", rule_candidate, finding.file, str(finding.line)) in baseline:
            return True
        if ("rfm", rule_candidate, finding.file, finding.match) in baseline:
            return True
        if ("rf", rule_candidate, finding.file) in baseline:
            return True
    return False


def write_baseline(report: ScanReport, output_path: str | Path) -> Path:
    """Write a `.vaultsweep-baseline` JSON file from `report`."""
    dest = Path(output_path)
    payload = {
        "tool": "VaultSweep",
        "version": __version__,
        "findings": [
            {
                "fingerprint": finding_fingerprint(f),
                "rule_id": f.rule_id,
                "file": f.file,
                "line": f.line,
                "match": f.match,
            }
            for f in report.findings
        ],
    }
    dest.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return dest


def _should_scan(path: Path) -> bool:
    if path.name == DEFAULT_BASELINE_FILENAME:
        return False
    if path.suffix.lower() in BINARY_EXTENSIONS:
        return False
    if path.suffix.lower() in SCAN_EXTENSIONS:
        return True
    # Extensionless config files
    if path.name in (".env", ".env.local", "config", "Makefile"):
        return True
    return False


def collect_files(target: Path) -> list[Path]:
    files: list[Path] = []
    if target.is_file():
        if _should_scan(target):
            files.append(target)
        return files

    for root, dirs, filenames in os.walk(target):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in filenames:
            p = Path(root) / name
            if _should_scan(p):
                files.append(p)
    return sorted(files)


def scan_file(file_path: Path, base: Path) -> list[Finding]:
    rel = str(file_path.relative_to(base)) if file_path.is_relative_to(base) else str(file_path)
    findings: list[Finding] = []
    try:
        content = file_path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return findings

    for line_no, line in enumerate(content.splitlines(), start=1):
        for rule in ALL_RULES:
            if is_line_ignored(line, rule.meta.rule_id):
                continue
            findings.extend(rule.scan_line(rel, line_no, line))
    return findings


def scan_path(
    target: str | Path,
    baseline_path: str | Path | None = None,
) -> ScanReport:
    path = Path(target).resolve()
    if not path.exists():
        raise FileNotFoundError(f"Target not found: {target}")

    base = path if path.is_dir() else path.parent
    resolved_baseline: Path | None = None
    if baseline_path is not None:
        resolved_baseline = Path(baseline_path)
    else:
        candidate = base / DEFAULT_BASELINE_FILENAME
        if candidate.is_file():
            resolved_baseline = candidate

    baseline_entries = load_baseline(resolved_baseline)
    files = collect_files(path)
    all_findings: list[Finding] = []

    for f in files:
        for finding in scan_file(f, base):
            if not is_suppressed_by_baseline(finding, baseline_entries):
                all_findings.append(finding)

    all_findings.sort(
        key=lambda x: (
            SEVERITY_ORDER[x.severity],
            x.file,
            x.line,
            x.rule_id,
        )
    )

    report = ScanReport(tool="VaultSweep", version=__version__, target=str(path))
    report.findings = all_findings
    report.files_scanned = len(files)
    report.rules_run = len(ALL_RULES)
    return report


def exceeds_threshold(findings: list[Finding], threshold: Severity) -> bool:
    threshold_rank = SEVERITY_ORDER[threshold]
    return any(SEVERITY_ORDER[f.severity] <= threshold_rank for f in findings)
